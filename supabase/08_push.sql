-- 1. Store each device's Expo push token on the member's profile.
alter table profiles
  add column if not exists expo_push_token text;

-- A member writing their own token is already permitted by the existing
-- profiles_update_self policy (it only constrains role/church_id changes),
-- so no new RLS is required.

