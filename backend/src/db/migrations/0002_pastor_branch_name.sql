-- Pastor applicants type the name of the branch they lead, but until now it had
-- nowhere to live: profiles.branch_id can only point at a branch that already
-- exists, and a member cannot create one (POST /branches is pastor+ only). The
-- name was collected by the app and dropped on the floor, so an approved pastor
-- landed in an app with no branch and someone had to create it by hand.
--
-- Holding the requested name here lets approval create the branch and link it in
-- one action. Kept after approval as the record of what was asked for.
--
-- Idempotent: db:migrate re-runs every file in this directory on every invocation.
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS pastor_branch_name text;
